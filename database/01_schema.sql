CREATE FUNCTION navigation_items_check_tree()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_parent_location varchar(10);
BEGIN
    IF NEW.parent_id IS NOT NULL THEN
        SELECT menu_location INTO v_parent_location FROM navigation_items WHERE id = NEW.parent_id;
        IF v_parent_location IS DISTINCT FROM NEW.menu_location THEN
            RAISE EXCEPTION 'navigation_items: item % (%) must share menu_location with parent % (%)',
                NEW.id, NEW.menu_location, NEW.parent_id, v_parent_location
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF NEW.menu_location IS DISTINCT FROM OLD.menu_location
           AND EXISTS (SELECT 1 FROM navigation_items WHERE parent_id = NEW.id) THEN
            RAISE EXCEPTION 'navigation_items: item % has children; move them before changing menu_location', NEW.id
                USING ERRCODE = 'check_violation';
        END IF;

        IF NEW.parent_id IS NOT NULL AND EXISTS (
            WITH RECURSIVE ancestors AS (
                SELECT n.id, n.parent_id FROM navigation_items n WHERE n.id = NEW.parent_id
                UNION
                SELECT n.id, n.parent_id FROM navigation_items n JOIN ancestors a ON n.id = a.parent_id
            )
            SELECT 1 FROM ancestors WHERE id = NEW.id
        ) THEN
            RAISE EXCEPTION 'navigation_items: parent_id % would create a cycle for id %', NEW.parent_id, NEW.id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER navigation_items_check_tree_trg
    BEFORE INSERT OR UPDATE OF parent_id, menu_location ON navigation_items
    FOR EACH ROW
    EXECUTE FUNCTION navigation_items_check_tree();


