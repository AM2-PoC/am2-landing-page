BEGIN;

DO $$
BEGIN
    IF to_regclass('directus_files') IS NULL THEN
        RAISE EXCEPTION 'The directus_files table does not exist. Run Directus once (bootstrap) before this file.';
    END IF;
END;
$$;

ALTER TABLE products
    ADD CONSTRAINT products_image_fkey
    FOREIGN KEY (image_id) REFERENCES directus_files (id) ON DELETE SET NULL;

ALTER TABLE content_sections
    ADD CONSTRAINT content_sections_image_fkey
    FOREIGN KEY (image_id) REFERENCES directus_files (id) ON DELETE SET NULL;

ALTER TABLE section_items
    ADD CONSTRAINT section_items_image_fkey
    FOREIGN KEY (image_id) REFERENCES directus_files (id) ON DELETE SET NULL;

CREATE TABLE file_translations (
    id                 integer       GENERATED BY DEFAULT AS IDENTITY,
    directus_files_id  uuid          NOT NULL,
    locale_code        varchar(10)   NOT NULL,
    alt_text           varchar(255)  NOT NULL,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT file_translations_pkey               PRIMARY KEY (id),
    CONSTRAINT file_translations_entity_locale_key  UNIQUE (directus_files_id, locale_code),
    CONSTRAINT file_translations_file_fkey          FOREIGN KEY (directus_files_id) REFERENCES directus_files (id) ON DELETE CASCADE,
    CONSTRAINT file_translations_locale_fkey        FOREIGN KEY (locale_code)       REFERENCES locales (code)       ON DELETE RESTRICT,
    CONSTRAINT file_translations_alt_text_chk       CHECK (btrim(alt_text) <> '')
);

CREATE TRIGGER file_translations_set_updated_at_trg
    BEFORE UPDATE ON file_translations
    FOR EACH ROW
    WHEN (OLD.* IS DISTINCT FROM NEW.*)
    EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE  file_translations IS 'Image alt text by language. For purely decorative images, use an empty attribute → alt="".';
COMMENT ON COLUMN file_translations.directus_files_id IS 'Image file → directus_files.id.';
COMMENT ON COLUMN file_translations.alt_text IS 'Image alt text (accessibility & SEO).';

COMMIT;
